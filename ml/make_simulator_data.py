"""
Training and test data generated by the project's OWN device simulator.

    python ml/make_simulator_data.py
writes ml/data/simulator/train_normal.jsonl and test.jsonl

Why this exists: a model must learn what *this fleet's* normal traffic looks like. The older
make_synthetic_data.py invents its own ranges (e.g. 12 requests/min), which are not what
ingestion/simulate_devices.py sends (1-6 per minute), so a model trained on it would flag every
real message. Here the data comes straight from the simulator's normal_reading() and
anomalous_reading(), so the model, the live traffic and the labels always agree.

Test rows carry _label (0 normal / 1 attack) and _attack (the simulator's attack type).
payload_tamper is left out on purpose: the gateway rejects it (HTTP 422) before it ever
reaches Kafka, so the model never sees it.
"""
import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "ingestion"))
import simulate_devices as sim  # noqa: E402  (reuses the simulator's own generators)

ATTACKS = ["out_of_range_vital", "traffic_flood", "prescription_mismatch"]


def _message(device: dict, metrics: dict, i: int) -> dict:
    return {
        "message_id": f"sim-{i}", "device_id": device["device_id"], "device_type": device["device_type"],
        "unit": device["unit"], "timestamp": datetime.now(timezone.utc).isoformat(), **metrics,
    }


def generate(n_normal=20000, n_test_normal=3000, n_test_attack=1500, seed=0):
    random.seed(seed)
    devices = sim.DEVICES
    train = [_message(d, sim.normal_reading(d), i) for i, d in ((i, random.choice(devices)) for i in range(n_normal))]

    test = []
    for i in range(n_test_normal):
        d = random.choice(devices)
        r = _message(d, sim.normal_reading(d), 10**6 + i)
        r["_label"], r["_attack"] = 0, "none"
        test.append(r)
    wanted = {a: n_test_attack // len(ATTACKS) for a in ATTACKS}
    i = 0
    while any(wanted.values()):
        d = random.choice(devices)
        metrics, attack, malformed = sim.anomalous_reading(d)
        if malformed or not wanted.get(attack):
            continue                       # skip payload_tamper and attacks we already have enough of
        wanted[attack] -= 1
        r = _message(d, metrics, 2 * 10**6 + i); i += 1
        r["_label"], r["_attack"] = 1, attack
        test.append(r)
    random.shuffle(test)
    return train, test


if __name__ == "__main__":
    out = HERE / "data" / "simulator"
    out.mkdir(parents=True, exist_ok=True)
    train, test = generate()
    for name, rows in (("train_normal.jsonl", train), ("test.jsonl", test)):
        with open(out / name, "w") as f:
            for r in rows:
                f.write(json.dumps(r) + "\n")
    print(f"Wrote {len(train)} normal training rows and {len(test)} test rows to {out}")
